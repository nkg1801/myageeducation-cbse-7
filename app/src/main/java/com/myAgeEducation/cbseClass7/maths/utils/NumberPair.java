package com.myAgeEducation.cbseClass7.maths.utils;

public class NumberPair
{
    private final int first;
    private final int second;

    public NumberPair(int first, int second)
    {
        this.first = first;
        this.second = second;
    }

    public int getFirst()
    {
        return first;
    }
    public int getSecond()
    {
        return second;
    }
}
