package com.myAgeEducation.cbseClass7.maths.fractions;

public class StoryTemplate
{
    public final String object;
    public final String action;
    public final String preposition;
    public final String questionEnding;

    public StoryTemplate(
            String object,
            String action,
            String preposition,
            String questionEnding)
    {
        this.object = object;
        this.action = action;
        this.preposition = preposition;
        this.questionEnding = questionEnding;
    }
}